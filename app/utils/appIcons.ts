export type AppIconId = keyof typeof ICONS;

/** the icon of an app id for the app bar and the menus: `sys://` symbol on iOS, vector drawable `res://ic_mdi_*` on Android (generated by scripts/generate-android-icons.mjs) */
export function appIcon(id: string) {
    const name = ICONS[id];
    if (!name) {
        return undefined;
    }
    return __IOS__ ? `sys://${name}` : `res://ic_mdi_${name.replace(/-/g, '_')}`;
}
